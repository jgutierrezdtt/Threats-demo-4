const dictionaries: Record<Exclude<Language, 'es'>, TranslationSet> = { en, de }
const reverseToSpanish = new Map<string, string>()

for (const dictionary of Object.values(dictionaries)) {
  for (const [spanish, translated] of Object.entries(dictionary)) {
    if (!reverseToSpanish.has(translated)) reverseToSpanish.set(translated, spanish)
  }
}

const originalText = new WeakMap<Text, string>()
const originalAttrs = new WeakMap<Element, Record<string, string>>()
let translating = false

function preserveWhitespace(source: string, translated: string) {
  const leading = source.match(/^\s*/)?.[0] ?? ''
  const trailing = source.match(/\s*$/)?.[0] ?? ''
  return `${leading}${translated}${trailing}`
}

function translatePhrase(phrase: string, language: Language) {
  const canonicalPhrase = reverseToSpanish.get(phrase) ?? phrase
  if (language === 'es') return canonicalPhrase
  const dictionary = dictionaries[language]
  if (dictionary[canonicalPhrase]) return dictionary[canonicalPhrase]

  let translated = canonicalPhrase
  for (const [from, to] of Object.entries(dictionary).sort((a, b) => b[0].length - a[0].length)) {
    translated = translated.split(from).join(to)
  }

  translated = translated
    .replace(/^Mostrando (\d+) eventos · Actualizado (.+)$/i, language === 'en' ? 'Showing $1 events · Updated $2' : '$1 Veranstaltungen · Aktualisiert $2')
    .replace(/^(\d+) productos disponibles$/i, language === 'en' ? '$1 products available' : '$1 Produkte verfügbar')
    .replace(/^(\d+) disp\.$/i, language === 'en' ? '$1 available' : '$1 verfügbar')
    .replace(/^Pagar (.+)$/i, language === 'en' ? 'Pay $1' : '$1 bezahlen')
    .replace(/^Descuento acumulado: (.+)%. ¡Precio especial aplicado!$/i, language === 'en' ? 'Accumulated discount: $1%. Special price applied!' : 'Kumulierter Rabatt: $1%. Sonderpreis angewendet!')
    .replace(/^Contratar ahora — (.+)$/i, language === 'en' ? 'Buy now — $1' : 'Jetzt abschließen — $1')
    .replace(/^Usuario: (.+)$/i, language === 'en' ? 'User: $1' : 'Benutzer: $1')
    .replace(/^No se encontraron resultados para «(.+)»$/i, language === 'en' ? 'No results found for “$1”' : 'Keine Ergebnisse für „$1“ gefunden')
    .replace(/^DNI: (.+) · Expediente: (.+)$/i, language === 'en' ? 'DNI: $1 · Record: $2' : 'DNI: $1 · Akte: $2')

  return translated
}

function translateTextNode(node: Text, language: Language) {
  const parent = node.parentElement
  if (!parent || parent.closest('script, style, textarea, pre, code, .terminal, .code-block')) return
  if (!originalText.has(node)) originalText.set(node, node.nodeValue ?? '')

  const source = originalText.get(node) ?? ''
  const phrase = source.trim()
  if (!phrase) return

  const translated = translatePhrase(phrase, language)
  const nextValue = preserveWhitespace(source, translated)
  if (node.nodeValue !== nextValue) node.nodeValue = nextValue
}

function translateAttributes(root: HTMLElement, language: Language) {
  const attrs = ['placeholder', 'title', 'aria-label']
  root.querySelectorAll<HTMLElement>('*').forEach(el => {
    if (el.closest('pre, code, .terminal, .code-block')) return
    const stored = originalAttrs.get(el) ?? {}
    attrs.forEach(attr => {
      const current = el.getAttribute(attr)
      if (current === null) return
      if (!stored[attr]) stored[attr] = current
      const translated = translatePhrase(stored[attr], language)
      if (current !== translated) el.setAttribute(attr, translated)
    })
    if (Object.keys(stored).length > 0) originalAttrs.set(el, stored)
  })
}

export function applyTranslations(root: HTMLElement, language: Language) {
  translating = true
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
  let node = walker.nextNode()
  while (node) {
    translateTextNode(node as Text, language)
    node = walker.nextNode()
  }
  translateAttributes(root, language)
  document.documentElement.lang = language
  translating = false
}

export function useDomTranslations(language: Language) {
  useEffect(() => {
    const root = document.getElementById('root')
    if (!root) return

    applyTranslations(root, language)
    let pending = false
    const observer = new MutationObserver(() => {
      if (translating || pending) return
      pending = true
      window.requestAnimationFrame(() => {
        pending = false
        applyTranslations(root, language)
      })
    })
    observer.observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ['placeholder', 'title', 'aria-label'] })
    return () => observer.disconnect()
  }, [language])
}

export function t(phrase: string, language: Language) {
  return translatePhrase(phrase, language)
}
